function at(seconds: number): number {
    return ORACLE_BASE_TIME + seconds * 1_000;
}

function makeTrade(
    aggregateTradeId: number,
    seconds: number,
    price: number,
    quantityBtc: number,
    aggressor: 'BUY' | 'SELL',
): ClassifiedTradeV1 {
    return {
        schemaVersion: ORDERFLOW_SCHEMA_VERSION,
        venue: 'BINANCE_SPOT',
        symbol: 'BTCUSDT',
        aggregateTradeId,
        firstTradeId: aggregateTradeId,
        lastTradeId: aggregateTradeId,
        eventTime: at(seconds),
        tradeTime: at(seconds),
        price,
        quantityBtc,
        notionalUsd: price * quantityBtc,
        aggressor,
        buyerIsMaker: aggressor === 'SELL',
    };
}

function makeCaptureStartBoundary(nextAggregateTradeId: number | null): TradeCaptureBoundaryV1 {
    return {
        schemaVersion: ORDERFLOW_SCHEMA_VERSION,
        boundaryId: 'capture-start',
        reason: 'CAPTURE_START',
        occurredAt: ORACLE_BASE_TIME,
        previousAggregateTradeId: null,
        nextAggregateTradeId,
        missingAggregateTradeCount: null,
    };
}

function makeAggregateIdGapBoundary(
    boundaryId: string,
    previousAggregateTradeId: number,
    nextAggregateTradeId: number,
): TradeCaptureBoundaryV1 {
    return {
        schemaVersion: ORDERFLOW_SCHEMA_VERSION,
        boundaryId,
        reason: 'AGGREGATE_ID_GAP',
        occurredAt: at(60),
        previousAggregateTradeId,
        nextAggregateTradeId,
        missingAggregateTradeCount: nextAggregateTradeId - previousAggregateTradeId - 1,
    };
}

function makeReconnectBoundary(boundaryId: string, previousAggregateTradeId: number): TradeCaptureBoundaryV1 {
    return {
        schemaVersion: ORDERFLOW_SCHEMA_VERSION,
        boundaryId,
        reason: 'RECONNECT',
        occurredAt: at(60),
        previousAggregateTradeId,
        nextAggregateTradeId: null,
        missingAggregateTradeCount: null,
    };
}

interface CaptureInput {
    trades: ClassifiedTradeV1[];
    boundaries?: TradeCaptureBoundaryV1[];
    capturedAt: number;
    eventTime: number;
    coverageStart: number | null;
    coverageEnd: number | null;
    sequenceState: CaptureCoverageV1['sequenceState'];
    gapCount: number;
}

function makeCapture(input: CaptureInput): AggregateTradeCaptureSnapshotV1 {
    const last = input.trades.length > 0 ? input.trades[input.trades.length - 1] : null;
    return {
        schemaVersion: ORDERFLOW_SCHEMA_VERSION,
        trades: input.trades,
        boundaries: input.boundaries ?? [makeCaptureStartBoundary(input.trades[0] ? input.trades[0].aggregateTradeId : null)],
        coverage: createCaptureCoverageV1({
            dataMode: 'REPLAY',
            source: 'UX16_FIXTURE',
            venue: 'BINANCE_SPOT',
            symbol: 'BTCUSDT',
            capturedAt: input.capturedAt,
            eventTime: input.eventTime,
            coverageStart: input.coverageStart,
            coverageEnd: input.coverageEnd,
            sequenceState: input.sequenceState,
            gapCount: input.gapCount,
            precision: 'TRADE',
            approximation: 'NONE',
        }),
        stats: {
            acceptedCount: input.trades.length,
            duplicateCount: 0,
            outOfOrderCount: 0,
            invalidCount: 0,
            reconnectCount: 0,
        },
        lastAggregateTradeId: last ? last.aggregateTradeId : null,
    };
}

